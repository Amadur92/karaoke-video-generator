"""
Низкоуровневая нормализация текста: транслитерация кириллицы, приведение к нижнему
регистру, удаление пунктуации/скобок. Вынесено в отдельный модуль, чтобы избежать
циклического импорта (scoring и markers зависят от нормализации).
"""
from __future__ import annotations

import re


CYR_TO_LAT = str.maketrans(
    {
        "а": "a",
        "б": "b",
        "в": "v",
        "г": "g",
        "д": "d",
        "е": "e",
        "ё": "e",
        "ж": "zh",
        "з": "z",
        "и": "i",
        "й": "y",
        "к": "k",
        "л": "l",
        "м": "m",
        "н": "n",
        "о": "o",
        "п": "p",
        "р": "r",
        "с": "s",
        "т": "t",
        "у": "u",
        "ф": "f",
        "х": "h",
        "ц": "ts",
        "ч": "ch",
        "ш": "sh",
        "щ": "sch",
        "ъ": "",
        "ы": "y",
        "ь": "",
        "э": "e",
        "ю": "yu",
        "я": "ya",
    }
)


def normalize(value: str) -> str:
    """
    Приводит строку к канонической форме для сравнения/матчинга:
    нижний регистр → транслитерация кириллицы → удаление скобок и пунктуации.
    """
    value = value.lower()
    value = value.translate(CYR_TO_LAT)
    value = re.sub(r"\([^)]*\)|\[[^]]*\]", " ", value)
    value = value.replace("&", " and ")
    value = re.sub(r"[^a-zа-яё0-9]+", " ", value, flags=re.IGNORECASE)
    return " ".join(value.split())


# Обратная транслитерация латиницы → кириллица для запросов к провайдерам.
# Используется, когда в исходных данных артист указан латиницей (Zemfira),
# а каталог (Deezer/ВКонтакте-стиль) лучше ищется по кириллице.
# Длинные диграфы должны идти раньше коротких, чтобы «zh» → «ж», а не «z»+»h».
_LAT_TO_CYR_PAIRS = [
    ("sch", "щ"),
    ("sh", "ш"),
    ("ch", "ч"),
    ("ya", "я"),
    ("yu", "ю"),
    ("ye", "е"),
    ("yo", "ё"),
    ("ts", "ц"),
    ("zh", "ж"),
    ("a", "а"), ("b", "б"), ("v", "в"), ("g", "г"), ("d", "д"),
    ("e", "е"), ("z", "з"), ("i", "и"), ("y", "й"), ("k", "к"),
    ("l", "л"), ("m", "м"), ("n", "н"), ("o", "о"), ("p", "п"),
    ("r", "р"), ("s", "с"), ("t", "т"), ("u", "у"), ("f", "ф"),
    ("h", "х"), ("'", "ь"),
    # «j» как й (Jusup → Юсуп в обратную сторону не работаем, но для часто
    # встречающихся латинских записей русских имён это полезно)
    ("j", "й"),
    # «w» и «x» — оставляем как есть (нет однозначного кириллического соответствия)
]


def translit_lat_to_cyr(value: str) -> str:
    """
    Грубая обратная транслитерация латиницы в кириллицу.
    Применяется к строкам, где кириллицы нет (значит, артист уже латинизирован),
    чтобы дать провайдерам второй вариант запроса.
    """
    if not value:
        return ""
    lower = value.lower()
    out: list[str] = []
    i = 0
    while i < len(lower):
        matched = False
        for lat, cyr in _LAT_TO_CYR_PAIRS:
            if lower.startswith(lat, i):
                out.append(cyr)
                i += len(lat)
                matched = True
                break
        if not matched:
            out.append(lower[i])
            i += 1
    return "".join(out)


def has_cyrillic(value: str) -> bool:
    """True, если в строке есть хотя бы один кириллический символ."""
    return bool(re.search("[а-яё]", value or "", flags=re.IGNORECASE))
